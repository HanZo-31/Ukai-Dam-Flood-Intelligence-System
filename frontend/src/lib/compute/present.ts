export interface Row { label: string; value: string; note?: string }
export const ROLE_TITLE: Record<Role, string> = {
  max_depth_cog: "Maximum depth (m)", arrival_time_cog: "Arrival time (minutes, hourly)", max_velocity_cog: "Maximum velocity (m/s)", extent_geojson: "Flood extent outline",
};
const m3 = (v: number) => `${v.toLocaleString("en-US")} m³/s`;
const sec = (v: number) => `${v.toLocaleString("en-US", { maximumFractionDigits: 3 })} s`;

export function identityRows(a: Accepted): Row[] {
  const r = a.result;
  return [
    { label: "Requested peak release", value: m3(r.requested_peak_release_m3s) },
    { label: "Actual peak release", value: m3(r.actual_peak_release_m3s), note: "Equal to the request; a different value is rejected, not substituted." },
    { label: "Engine", value: `${r.engine} (${r.engine_version})` },
    { label: "Computed by the service", value: r.computed ? "Yes — generated by the native solver (may be reused from cache)" : "No" },
    { label: "Served from cache", value: r.cache_hit ? "Yes — an earlier identical computation was reused" : "No — computed for this request" },
    { label: "Calibration", value: r.calibration_status },
    { label: "Scientifically validated", value: r.scientifically_validated ? "Yes" : "No" },
    { label: "Run ID", value: r.run_id }, { label: "Scenario ID", value: r.scenario_id },
    { label: "Job ID", value: r.job_id }, { label: "Request ID", value: r.request_id },
    { label: "Configuration", value: `${r.configuration_id} · ${r.configuration_checksum}` },
    { label: "Compared with reference scenario", value: r.derived_grid.target_reference_scenario_id },
    { label: "Native results checksum", value: r.native_results_checksum },
    { label: "Velocity definition", value: r.velocity_definition ?? "Unavailable", note: "A face-normal component is not speed magnitude; no cross-engine velocity difference is calculated." },
    { label: "Displayed grid pixels", value: `${r.derived_grid.transform[0].toFixed(3)} × ${Math.abs(r.derived_grid.transform[4]).toFixed(3)} m`, note: "Nearest-neighbour derivatives of the native approximately 100 m solver grid. Finer display pixels do not improve hydraulic resolution." },
  ];
}
export const TIMING_NOTE = "Service-side times from the request to checked products being available. They exclude downloading, decoding and drawing in this browser, and are not a promise about future run times. For a cached result these are the original generation times, not the current cache lookup duration.";
export function timingRows(r: ResultV2): Row[] {
  const t = r.timings;
  return [
    { label: "Prepare inputs", value: sec(t.prepare_seconds) }, { label: "Solver", value: sec(t.solver_seconds) },
    { label: "Package check", value: sec(t.package_check_seconds) }, { label: "Availability check", value: sec(t.availability_seconds) },
    { label: "Request to checked products", value: sec(t.request_to_assets_seconds), note: `Scope: ${t.scope}` },
  ];
}
export interface AssetRow { role: Role; title: string; status: "received" | "unavailable"; detail: string }
export function assetRows(a: Accepted): AssetRow[] {
  const d = a.products.decoded;
  return ROLES.map((role) => {
    const asset = a.result.assets[role], reason = a.result.unavailable_reasons[role];
    const entry = a.products.entries[role];
    const slot = role === "max_depth_cog" ? d?.depth : role === "arrival_time_cog" ? d?.arrival : role === "max_velocity_cog" ? d?.velocity : d?.extent;
    if (!asset) return { role, title: ROLE_TITLE[role], status: "unavailable" as const, detail: reason ?? "The service did not provide this product." };
    if (slot) return { role, title: ROLE_TITLE[role], status: "received" as const, detail: `${asset.bytes.toLocaleString("en-US")} bytes, checksum verified (${asset.sha256.slice(0, 15)}…)` };
    const why = d?.unavailable[role] ?? (entry && entry.status === "rejected" ? entry.message : entry && entry.status === "not_offered" ? entry.reason : "The product could not be used.");
    return { role, title: ROLE_TITLE[role], status: "unavailable" as const, detail: why };
  });
}

// ---- drawing --------------------------------------------------------------------------------------------------------------
const stops = (mode: "depth" | "arrival" | "velocity") => SCALES[mode].stops.map(([v, hex]) => [v, ...hexToRgb(hex)] as [number, number, number, number]);
const DEPTH_STOPS = stops("depth"), ARRIVAL_STOPS = stops("arrival"), VELOCITY_STOPS = stops("velocity");
function colourAt(table: [number, number, number, number][], v: number): [number, number, number] {
  let k = 0;
  for (let i = 0; i < table.length; i++) if (v >= table[i][0]) k = i;
  return [table[k][1], table[k][2], table[k][3]];
}
/** RGBA bytes for one raster. Dry cells are left unshaded; nodata is drawn as a distinct neutral grey so unknown is never mistaken for dry or zero. */
export function rasterRgba(g: ProductGrid, mode: "depth" | "arrival" | "velocity"): Uint8ClampedArray {
  const out = new Uint8ClampedArray(g.width * g.height * 4);
  const table = mode === "depth" ? DEPTH_STOPS : mode === "velocity" ? VELOCITY_STOPS : ARRIVAL_STOPS, div = SCALES[mode].divisor;
  for (let i = 0; i < g.data.length; i++) {
    const v = g.data[i];
    if (v === -9999 || !Number.isFinite(v) || v < 0) { out.set([120, 130, 140, 150], i * 4); continue; }
    if (mode === "depth" && v <= Math.fround(0.1)) continue; // dry (<= 0.1 m) stays transparent
    const [r, gg, b] = colourAt(table, v / div);
    out.set([r, gg, b, 225], i * 4);
  }
  return out;
}
export function classRgba(classes: Uint8Array): Uint8ClampedArray {
  const out = new Uint8ClampedArray(classes.length * 4);
  for (let i = 0; i < classes.length; i++) { const c = CANDIDATE_CLASS_COLOURS[classes[i]]; if (c && c[3]) out.set(c as number[], i * 4); }
  return out;
}
